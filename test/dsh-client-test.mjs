#!/usr/bin/env node
/**
 * Offline checks for the DSH client half (dsh-plugin/client.js).
 *
 * The client bundle is generated, so two failure modes matter and neither needs
 * a running Desktop:
 *   1. the checked-in bundle drifts from client.template.js + uart-ui.js;
 *   2. the generated module no longer registers the slots the app expects, or a
 *      section throws while rendering.
 *
 * Run: node test/dsh-client-test.mjs
 */
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import vm from 'node:vm'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const read = (path) => readFileSync(join(root, path), 'utf8')

let failures = 0
function check(name, fn) {
  try {
    fn()
    process.stdout.write(`ok: ${name}\n`)
  } catch (error) {
    failures += 1
    process.stdout.write(`FAIL: ${name}\n  ${String(error?.message ?? error).split('\n').join('\n  ')}\n`)
  }
}

// ── 1. generated bundle is current ─────────────────────────────────────────
function generate() {
  const ui = read('src/hub/public/uart-ui.js')
    .replace(/^export function createUartUi/m, 'function createUartUi')
    .trimEnd()
  const template = read('dsh-plugin/client.template.js')
  const banner =
    '/* GENERATED by scripts/build-dsh-client.mjs — edit client.template.js or src/hub/public/uart-ui.js */\n'
  const pad = ' '.repeat(4)
  const indented = ui
    .split('\n')
    .map((line) => (line.trim().length === 0 ? line : pad + line))
    .join('\n')
  return banner + template.replace('    //__UART_UI__', () => indented)
}

check('client.js matches a fresh build of template + uart-ui.js', () => {
  assert.equal(read('dsh-plugin/client.js'), generate())
})

// ── 2. the generated module loads and registers its slots ──────────────────
const store = new Map()
const listeners = { window: 0 }
const fakeWindow = {
  innerWidth: 1338,
  innerHeight: 802,
  localStorage: {
    getItem: (key) => (store.has(key) ? store.get(key) : null),
    setItem: (key, value) => store.set(key, String(value)),
  },
  addEventListener: () => {},
  removeEventListener: () => {},
}
const fakeDocument = {
  createElement: () => ({ style: {}, addEventListener: () => {}, setAttribute: () => {}, appendChild: () => {} }),
  baseURI: 'dsh-app://app/',
}
const fakeReact = {
  createElement: (type, props, ...children) => ({ type, props: { ...(props ?? {}), children } }),
  useState: (initial) => [typeof initial === 'function' ? initial() : initial, () => {}],
  useEffect: () => {},
  useRef: (initial) => ({ current: initial ?? null }),
  useCallback: (fn) => fn,
}
const registrations = []
const fakeContext = {
  effect: (fn) => {
    const dispose = fn()
    return typeof dispose === 'function' ? dispose : () => {}
  },
  locale: {
    register: () => () => {},
    bind: () => (key) => `#${key}`,
    getLocale: () => ({ id: 'zh' }),
  },
  slots: {
    inject: (_name, run) => {
      run()
      return () => {}
    },
    register: (options, component) => {
      registrations.push({ options, component })
      return () => {}
    },
  },
}

let loaded
const sandbox = {
  window: { ...fakeWindow, __ModuleLoader__: { load: (entry) => (loaded = entry) } },
  document: fakeDocument,
  console,
}
sandbox.globalThis = sandbox
vm.createContext(sandbox)
vm.runInContext(read('dsh-plugin/client.js'), sandbox, { filename: 'dsh-plugin/client.js' })

check('client.js is a single loaded module with no dynamic import', () => {
  assert.ok(loaded, 'window.__ModuleLoader__.load was never called')
  assert.equal(loaded.id, '@local/dsh-uart')
  assert.ok(!/\bimport\s*\(/.test(read('dsh-plugin/client.js')), 'dynamic import() would be refused on dsh-app://')
})

const plugin = loaded.factory((name) => {
  if (name === 'react') return fakeReact
  throw new Error(`unexpected require: ${name}`)
})

check('apply() registers the panel, the float slot and the settings section', () => {
  plugin.apply(fakeContext)
  const summary = registrations.map((entry) => `${entry.options.name}:${entry.options.id ?? entry.options.key}`)
  for (const expected of ['sidebar.panellist:uart', 'main:uart', 'shell.overlay:uart-float', 'settings.section:uart-console']) {
    assert.ok(summary.includes(expected), `missing slot registration ${expected} (got ${summary.join(', ')})`)
  }
  for (const entry of registrations) assert.equal(typeof entry.component, 'function', `${entry.options.name} has no component`)
})

check('settings section renders both placements and switches one', () => {
  const section = registrations.find((entry) => entry.options.name === 'settings.section')
  const props = section.options.inject()
  assert.equal(typeof props.locale, 'string')
  assert.equal(typeof props.t, 'function')

  const render = (node) => {
    if (node === null || node === undefined || typeof node !== 'object') return node
    if (Array.isArray(node)) return node.map(render)
    if (typeof node.type === 'function') return render(node.type(node.props))
    return { ...node, props: { ...node.props, children: (node.props.children ?? []).map(render) } }
  }
  const textOf = (node) => {
    if (typeof node === 'string' || typeof node === 'number') return String(node)
    if (!node || typeof node !== 'object') return ''
    if (Array.isArray(node)) return node.map(textOf).join('')
    return textOf(node.props?.children ?? [])
  }
  const cardsOf = (tree) => {
    const found = []
    const walk = (node) => {
      if (!node || typeof node !== 'object') return
      if (Array.isArray(node)) return node.forEach(walk)
      // Placement cards carry an explicit marker; the decode row's format
      // buttons are aria-pressed as well but are not placements.
      if (node.type === 'button' && node.props?.['data-uart-placement'] === 'true') found.push(node)
      ;(node.props?.children ?? []).forEach(walk)
    }
    walk(tree)
    return found
  }

  const first = render(section.component(props))
  const text = textOf(first)
  for (const key of ['#settingsTitle', '#optionPanel', '#optionFloat']) {
    assert.ok(text.includes(key), `settings section is missing ${key}`)
  }
  const cards = cardsOf(first)
  assert.equal(cards.length, 2, 'expected two placement cards')
  assert.equal(cards[0].props['aria-pressed'], 'true', 'panel placement should start selected')
  assert.equal(cards[1].props['aria-pressed'], 'false')

  cards[1].props.onClick()
  assert.equal(store.get('dsh-uart.display-mode'), 'float', 'choosing the float placement must persist')

  const second = cardsOf(render(section.component(props)))
  assert.equal(second[0].props['aria-pressed'], 'false')
  assert.equal(second[1].props['aria-pressed'], 'true', 'the choice must be reflected on the next render')
})

check('settings section offers the Agent tool switch', () => {
  const section = registrations.find((entry) => entry.options.name === 'settings.section')
  const props = section.options.inject()

  const render = (node) => {
    if (node === null || node === undefined || typeof node !== 'object') return node
    if (Array.isArray(node)) return node.map(render)
    if (typeof node.type === 'function') return render(node.type(node.props))
    return { ...node, props: { ...node.props, children: (node.props.children ?? []).map(render) } }
  }
  const textOf = (node) => {
    if (typeof node === 'string' || typeof node === 'number') return String(node)
    if (!node || typeof node !== 'object') return ''
    if (Array.isArray(node)) return node.map(textOf).join('')
    return textOf(node.props?.children ?? [])
  }
  const switchesOf = (tree) => {
    const found = []
    const walk = (node) => {
      if (!node || typeof node !== 'object') return
      if (Array.isArray(node)) return node.forEach(walk)
      if (node.props?.role === 'switch') found.push(node)
      ;(node.props?.children ?? []).forEach(walk)
    }
    walk(tree)
    return found
  }

  const tree = render(section.component(props))
  const text = textOf(tree)
  assert.ok(text.includes('#optionAgentTool'), 'the Agent tool switch must be described in settings')
  const switches = switchesOf(tree)
  assert.equal(switches.length, 3, `expected three switches (agent, dock chip, follow), got ${switches.length}`)
  assert.equal(typeof switches[0].props.onClick, 'function', 'the Agent switch must be operable')
})

check('the float window rect is clamped into the current viewport', () => {
  const source = read('dsh-plugin/client.template.js')
  assert.match(source, /function loadRect\(\)[\s\S]*?Math\.min\(Math\.max\(wanted\.x, 8\)/, 'loadRect must clamp a restored rect')
})

if (failures > 0) {
  process.stdout.write(`\n${failures} check(s) failed\n`)
  process.exit(1)
}
process.stdout.write('\n=== DSH client offline tests done ===\n')
