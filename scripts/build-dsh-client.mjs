#!/usr/bin/env node
/**
 * Build the DSH client module.
 *
 * One source of truth: src/hub/public/uart-ui.js is loaded directly by the
 * standalone Hub page and inlined here for the DSH client, which cannot import
 * modules from the `dsh-app://` scheme used by DSH Desktop.
 *
 *   dsh-plugin/client.template.js  +  src/hub/public/uart-ui.js
 *        → dsh-plugin/client.js
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const uiFile = join(root, 'src/hub/public/uart-ui.js')
const templateFile = join(root, 'dsh-plugin/client.template.js')
const outputFile = join(root, 'dsh-plugin/client.js')

const ui = readFileSync(uiFile, 'utf8')
  .replace(/^export function createUartUi/m, 'function createUartUi')
  .trimEnd()

if (!ui.includes('function createUartUi')) {
  throw new Error('uart-ui.js no longer exports createUartUi; update the build script')
}

const template = readFileSync(templateFile, 'utf8')
if (!template.includes('//__UART_UI__')) {
  throw new Error('client.template.js is missing the //__UART_UI__ marker')
}

const banner =
  "/* GENERATED by scripts/build-dsh-client.mjs — edit client.template.js or src/hub/public/uart-ui.js */\n"
const output = banner + template.replace('    //__UART_UI__', () => indented(ui, 4))

function indented(source, spaces) {
  const pad = ' '.repeat(spaces)
  return source
    .split('\n')
    .map((line) => (line.trim().length === 0 ? line : pad + line))
    .join('\n')
}

writeFileSync(outputFile, output)
process.stdout.write(`dsh-plugin/client.js ← uart-ui.js (${ui.length} bytes) + template\n`)
